import * as fs from 'fs';
import { getMediaMime } from '../../../../base/common/mime.js';
import { URI } from '../../../../base/common/uri.js';
import { isAgentFeedbackAnnotationsAttachment, renderAgentFeedbackAnnotationsAttachment } from '../../common/meta/agentFeedbackAttachments.js';
import { readDispatchMarksMeta, renderDispatchMarksText } from '../../common/meta/dispatchMarksAttachmentMeta.js';
import { applyDispatchQuotes } from '../../common/meta/dispatchQuoteAttachmentMeta.js';
import { isHostSnapshotAttachment, readHostSnapshotAttachmentMeta } from '../../common/meta/agentSnapshotAttachmentMeta.js';
import { MessageAttachmentKind, type MessageAttachment, type MessageResourceAttachment } from '../../common/state/protocol/state.js';

/**
 * Build the {@link Anthropic.ContentBlockParam}[] payload for an
 * {@link SDKUserMessage} from a plain text prompt and the protocol
 * attachments accompanying the user message.
 *
 * Phase 6 keeps the resolver pure and minimal: a single `text` block
 * carrying the prompt, plus additional text blocks for attachments. This
 * mirrors the production extension's resolver shape so a future phase that
 * adds image rendering or inline range substitution can extend without
 * restructuring.
 *
 * Selections are rendered as URI references with an optional line
 * suffix. The protocol's {@link TextSelection} carries range metadata
 * only; the selected text is not included inline.
 *
 * Resource attachments and simple attachments with model representations
 * are honoured today. Embedded resources are dropped because the current
 * Claude path does not have a place to consume them.
 */
export function resolvePromptToContentBlocks(
	promptText: string,
	allAttachments?: readonly MessageAttachment[],
): Anthropic.ContentBlockParam[] {
	// Dispatch IDE: quotes (Quote, ⇧⌘L) go in front of the message as `>` paragraphs.
	const { prompt, attachments } = applyDispatchQuotes(promptText, allAttachments);
	const blocks: Anthropic.ContentBlockParam[] = [{ type: 'text', text: prompt }];
	if (!attachments?.length) {
		return blocks;
	}
	const refLines: string[] = [];
	const simpleBlocks: string[] = [];
	const feedbackBlocks: string[] = [];
	const imageBlocks: Anthropic.ContentBlockParam[] = [];
	let imageCount = 0;
	// Dispatch IDE: boxes drawn on a picture (draw-and-ask) go right after it: their coordinates and
	// the sentence under each, numbered like the picture's own boxes.
	const pushImage = (image: Anthropic.ImageBlockParam, att: MessageAttachment) => {
		imageBlocks.push(image);
		imageCount++;
		const marks = readDispatchMarksMeta(att);
		if (marks) {
			imageBlocks.push({ type: 'text', text: renderDispatchMarksText(marks, imageCount) });
		}
	};
	for (const att of attachments) {
		if (isAgentFeedbackAnnotationsAttachment(att)) {
			const rendered = renderAgentFeedbackAnnotationsAttachment(att);
			if (rendered) {
				feedbackBlocks.push(rendered);
			}
			continue;
		}
		if (att.type === MessageAttachmentKind.Simple) {
			if (att.modelRepresentation) {
				simpleBlocks.push(att.modelRepresentation);
			}
			continue;
		}
		// Dispatch IDE: a pasted or dropped image arrives as an embedded resource with its bytes; send it
		// as an image block so Claude sees it.
		if (att.type === MessageAttachmentKind.EmbeddedResource) {
			const image = toDispatchImageBlock(att.data, att.contentType);
			if (image) {
				pushImage(image, att);
			}
			continue;
		}
		if (att.type !== MessageAttachmentKind.Resource) {
			continue;
		}
		const uri = URI.parse(att.uri);
		// Dispatch IDE: the host snapshots a pasted image to a file before the harness sees it; read it and
		// send an image block (Codex sends the same file as localImage).
		if (uri.scheme === 'file' && isDispatchImageResource(att, uri)) {
			const image = readDispatchImageFile(uri.fsPath);
			if (image) {
				pushImage(image, att);
				continue;
			}
		}
		// A host-created snapshot (pasted content, unsaved editor, git: diff, …) is read-only context;
		// annotate the path inline so the model doesn't edit the copy (#331154). This is an advisory
		// signal: the host attachments-dir write-deny only fires for interactive permission prompts, so
		// it does NOT cover Claude's acceptEdits/bypassPermissions/auto modes or subagent inner tools.
		const readonlySuffix = isHostSnapshotAttachment(att) ? ' (read-only snapshot — do not edit this file)' : '';
		if (att.displayKind === 'selection') {
			const startLine = att.selection ? `:${att.selection.range.start.line + 1}` : '';
			refLines.push(`- ${uriToString(uri)}${startLine}${readonlySuffix}`);
		} else {
			refLines.push(`- ${uriToString(uri)}${readonlySuffix}`);
		}
	}
	blocks.push(...imageBlocks);
	if (feedbackBlocks.length > 0) {
		blocks.push({
			type: 'text',
			text: feedbackBlocks.join('\n\n'),
		});
	}
	if (simpleBlocks.length > 0) {
		blocks.push({
			type: 'text',
			text: simpleBlocks.join('\n\n'),
		});
	}
	if (refLines.length === 0) {
		return blocks;
	}
	blocks.push({
		type: 'text',
		text: '<system-reminder>\nThe user provided the following references:\n' +
			refLines.join('\n') +
			'\n\nIMPORTANT: this context may or may not be relevant to your tasks. ' +
			'You should not respond to this context unless it is highly relevant to your task.\n' +
			'</system-reminder>',
	});
	return blocks;
}

type DispatchImageMediaType = 'image/png' | 'image/jpeg' | 'image/gif' | 'image/webp';

/**
 * Dispatch IDE: an image block for base64 image bytes, or undefined when they are not an image the
 * Messages API takes. The media type comes from the bytes: the chat input re-encodes pasted images
 * to PNG or JPEG but keeps the original content type (a pasted BMP arrives labelled image/bmp).
 */
function toDispatchImageBlock(data: string, contentType: string): Anthropic.ImageBlockParam | undefined {
	if (!contentType.toLowerCase().startsWith('image/')) {
		return undefined;
	}
	const head = atob(data.slice(0, 24));
	let mediaType: DispatchImageMediaType | undefined;
	if (head.startsWith('\x89PNG')) {
		mediaType = 'image/png';
	} else if (head.startsWith('\xFF\xD8\xFF')) {
		mediaType = 'image/jpeg';
	} else if (head.startsWith('GIF8')) {
		mediaType = 'image/gif';
	} else if (head.startsWith('RIFF') && head.slice(8, 12) === 'WEBP') {
		mediaType = 'image/webp';
	}
	return mediaType ? { type: 'image', source: { type: 'base64', media_type: mediaType, data } } : undefined;
}

function isDispatchImageResource(att: MessageResourceAttachment, uri: URI): boolean {
	const contentType = att.contentType ?? readHostSnapshotAttachmentMeta(att)?.contentType ?? getMediaMime(uri.path);
	return att.displayKind === 'image' || contentType?.startsWith('image/') === true;
}

/** Dispatch IDE: an image block for an image file, or undefined when it can't be read or isn't PNG / JPEG / GIF / WebP. */
function readDispatchImageFile(path: string): Anthropic.ImageBlockParam | undefined {
	try {
		return toDispatchImageBlock(fs.readFileSync(path).toString('base64'), 'image/*');
	} catch {
		return undefined;
	}
}

function uriToString(uri: URI): string {
	return uri.scheme === 'file' ? uri.fsPath : uri.toString();
}
