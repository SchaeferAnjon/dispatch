import assert from 'assert';
import { URI } from '../../../../../base/common/uri.js';
import { ensureNoDisposablesAreLeakedInTestSuite } from '../../../../../base/test/common/utils.js';
import { toHostSnapshotAttachmentMeta } from '../../../common/meta/agentSnapshotAttachmentMeta.js';
import { toDispatchMarksMeta } from '../../../common/meta/dispatchMarksAttachmentMeta.js';
import { DispatchQuoteDisplayKind, IDispatchQuoteSource, toDispatchQuoteMeta } from '../../../common/meta/dispatchQuoteAttachmentMeta.js';
import { MessageAttachmentKind, type MessageAttachment } from '../../../common/state/protocol/state.js';
import { resolvePromptToContentBlocks } from '../../../node/claude/claudePromptResolver.js';

suite('claudePromptResolver', () => {

	ensureNoDisposablesAreLeakedInTestSuite();

	function referencesText(prompt: string, attachments: MessageAttachment[]): string {
		return resolvePromptToContentBlocks(prompt, attachments)
			.map(block => (block as { text?: string }).text ?? '')
			.join('\n');
	}

	test('a host-created snapshot path is annotated read-only, a normal file reference is not (#331154)', () => {
		const snapshotUri = URI.file('/data/attachments/id/Pasted text #1.txt');
		const snapshot: MessageAttachment = {
			type: MessageAttachmentKind.Resource,
			label: 'Pasted text #1',
			displayKind: 'document',
			uri: snapshotUri.toString(),
			_meta: toHostSnapshotAttachmentMeta('text/plain'),
		} as MessageAttachment;
		const fileUri = URI.file('/workspace/real.txt');
		const normal: MessageAttachment = {
			type: MessageAttachmentKind.Resource,
			label: 'real.txt',
			displayKind: 'document',
			uri: fileUri.toString(),
		} as MessageAttachment;

		const text = referencesText('trim this', [snapshot, normal]);

		assert.ok(text.includes(`- ${snapshotUri.fsPath} (read-only snapshot — do not edit this file)`), `text: ${text}`);
		assert.ok(text.includes(`- ${fileUri.fsPath}`) && !text.includes(`- ${fileUri.fsPath} (read-only`), `text: ${text}`);
	});

	test('Dispatch IDE: a pasted image becomes an image block typed by its bytes, other embedded bytes are dropped', () => {
		const png = btoa('\x89PNG\r\n\x1a\n' + 'rest-of-png');
		const jpegLabelledBmp = btoa('\xFF\xD8\xFF\xE0' + 'rest-of-jpeg');
		const pdf = btoa('%PDF-1.7 rest');
		const blocks = resolvePromptToContentBlocks('what is this', [
			{ type: MessageAttachmentKind.EmbeddedResource, label: 'Pasted Image', displayKind: 'image', data: png, contentType: 'image/png' },
			{ type: MessageAttachmentKind.EmbeddedResource, label: 'Pasted Image 2', displayKind: 'image', data: jpegLabelledBmp, contentType: 'image/bmp' },
			{ type: MessageAttachmentKind.EmbeddedResource, label: 'doc.pdf', data: pdf, contentType: 'application/pdf' },
		] as MessageAttachment[]);
		assert.deepStrictEqual(blocks, [
			{ type: 'text', text: 'what is this' },
			{ type: 'image', source: { type: 'base64', media_type: 'image/png', data: png } },
			{ type: 'image', source: { type: 'base64', media_type: 'image/jpeg', data: jpegLabelledBmp } },
		]);
	});

	test('Dispatch IDE: boxes drawn on a picture go right after it, numbered by picture', () => {
		const png = btoa('\x89PNG\r\n\x1a\n' + 'rest-of-png');
		const marked: MessageAttachment = {
			type: MessageAttachmentKind.EmbeddedResource, label: 'Pasted Image 2', displayKind: 'image', data: png, contentType: 'image/png',
			_meta: toDispatchMarksMeta({ v: 1, size: [800, 600], marks: [{ n: 1, box: [10, 20, 30, 40], color: 'red', note: 'this one' }], source: 'where.png' }),
		} as MessageAttachment;
		const blocks = resolvePromptToContentBlocks('look', [
			{ type: MessageAttachmentKind.EmbeddedResource, label: 'Pasted Image', displayKind: 'image', data: png, contentType: 'image/png' } as MessageAttachment,
			marked,
		]);
		assert.deepStrictEqual(blocks.map(b => b.type), ['text', 'image', 'image', 'text']);
		const text = (blocks[3] as { text: string }).text;
		assert.strictEqual(text, 'Marks on image 2 (800×600 px, origin top-left, x y w h):\n1 red 10 20 30 40  this one\nSource: where.png');
	});

	function dispatchQuote(text: string, source: IDispatchQuoteSource): MessageAttachment {
		return { type: MessageAttachmentKind.Simple, label: text, displayKind: DispatchQuoteDisplayKind, modelRepresentation: text, _meta: toDispatchQuoteMeta({ v: 1, text, source }) } as MessageAttachment;
	}

	test('Dispatch IDE: quotes go in front of the message as > paragraphs, a file quote names its line first', () => {
		const blocks = resolvePromptToContentBlocks('turn both around', [
			dispatchQuote('subtasks (the parent is counted once)', { from: 'reply', label: 'Claude · 4:20 AM', chat: 'c', responseId: 'r' }),
			dispatchQuote('Subtasks: counted once.\nSecond line', { from: 'diff', label: 'NOTES.md:9-10', file: 'NOTES.md', startLine: 9, endLine: 10 }),
		]);
		assert.deepStrictEqual(blocks, [{
			type: 'text',
			text: '> subtasks (the parent is counted once)\n\nNOTES.md:9-10\n> Subtasks: counted once.\n> Second line\n\nturn both around',
		}]);
	});
});
